def code(d):
    d.network("Start with delay")
    a = d.fn("AND", "START", d.neg("STOP"))
    t = d.fb("TON1", "TON", IN=a, PT="T#5s")
    d.out("RUN", t["Q"])
    d.network("Level")
    s = d.fn("ADD", "LEVEL", "OFFSET", "0.5")
    d.out("TOTAL", s)
    lim = d.fb("LIM1", "FB_LIMITS", VALUE=s, LOW_LIMIT="10.0", HIGH_LIMIT="40.0")
    sel = d.fn("SEL", a, "SETPOINT_NIGHT", "SETPOINT_DAY")
    d.out("SETPOINT", sel)
    o = d.fn("OR", lim["TOO_LOW"], lim["TOO_HIGH"], t["Q"])
    d.out("ALARM", o)
    d.out("HIGH", lim["TOO_HIGH"])
    d.rung("START", d.par("A", ["B", "/C"]), coils=["LAMP", "S:LATCH"])
    d.rung("RUN", d.fb("TON2", "TON", PT="T#2s"), coils=["R:LATCH"])
